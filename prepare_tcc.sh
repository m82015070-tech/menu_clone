#!/bin/bash
# prepare_tcc.sh <tinycc_dir> <plugin_source_dir> <list_file>
# Builds TinyCC INTO the plugin as one translation unit (tcc_unity.c) so that C scripts can be compiled at runtime.
# Every file this script creates is written to <list_file> so the workflow can remove them again if the TinyCC build fails.
T="$1"; S="$2"; LIST="$3"
: > "$LIST"
add() { echo "$1" >> "$LIST"; }

if [ ! -f "$T/libtcc.c" ]; then
    echo "prepare_tcc: TinyCC sources not found in $T -> building WITHOUT C scripts"
    echo "" > "$S/have_tcc.h"
    exit 0
fi

echo "prepare_tcc: TinyCC found:"; ls "$T" | tr '\n' ' '; echo

# 1) .c files that libtcc.c includes (ONE_SOURCE build) -> renamed to .cinc so the plugin Makefile does not compile them alone,
#    and every  #include "xxx.c"  is redirected to the renamed copy.
for f in libtcc tccpp tccgen tccdbg tccelf tccasm tccrun x86_64-gen x86_64-link i386-asm; do
    if [ -f "$T/$f.c" ]; then
        sed -E 's/#[[:space:]]*include[[:space:]]+"([A-Za-z0-9_-]+)\.c"/#include "tcc_\1.cinc"/' "$T/$f.c" > "$S/tcc_$f.cinc"
        add "$S/tcc_$f.cinc"
    fi
done

# 2) headers (tcc.h, libtcc.h, tcctok.h, elf.h, x86_64-asm.h ...)
for h in "$T"/*.h; do
    b=$(basename "$h")
    cp "$h" "$S/$b"; add "$S/$b"
done

# 3) tccdefs_.h : include/tccdefs.h turned into a list of C string literals (this is what TinyCC's own c2str tool does)
if [ -f "$T/include/tccdefs.h" ]; then
    sed -e 's/\\/\\\\/g' -e 's/"/\\"/g' -e 's/^/"/' -e 's/$/\\n"/' "$T/include/tccdefs.h" > "$S/tccdefs_.h"
    add "$S/tccdefs_.h"
fi

# 4) TinyCC's own config.h (our menu config header is called menu_config.h, so there is no clash)
cat > "$S/config.h" <<'EOF'
#ifndef TCC_PLUGIN_CONFIG_H
#define TCC_PLUGIN_CONFIG_H
#define TCC_VERSION "0.9.28rc"
#define CONFIG_TCCDIR "/data/16menu/tcc"
#define CONFIG_TCC_STATIC 1
#define CONFIG_TCC_SEMLOCK 0
#endif
EOF
add "$S/config.h"

# 5) the single C translation unit
cat > "$S/tcc_unity.c" <<'EOF'
/* Generated by prepare_tcc.sh: TinyCC built as ONE translation unit inside the PS4 plugin. */
#define TCC_TARGET_X86_64 1
#define ONE_SOURCE 1
#include <stddef.h>
#include <stdlib.h>
#include <string.h>
#include <stdio.h>
#include <sys/mman.h>
#include <setjmp.h>
/* TinyCC calls mprotect() to make the relocated script executable: use the PS4 kernel call instead. */
extern int sceKernelMprotect(void* addr, size_t len, int prot);
#define mprotect(a, l, p) sceKernelMprotect((a), (l), (p))
#include "tcc_libtcc.cinc"
EOF
add "$S/tcc_unity.c"

echo "#define HAVE_TCC 1" > "$S/have_tcc.h"
echo "prepare_tcc: done, $(wc -l < "$LIST") files prepared"
